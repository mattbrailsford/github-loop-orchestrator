import { test } from 'node:test';
import assert from 'node:assert/strict';
import { validateConfig } from '../src/config.mjs';
import { extractAddressedRequest, findAddress } from '../src/mentions.mjs';
import { matchEvent } from '../src/match.mjs';
import { HUB, baseConfig, commentEvent, fakeLookup, issueEvent } from './helpers.mjs';

const PREFIXES = ['🤖', ':robot:'];
const addressed = (text) => findAddress(text, PREFIXES) !== null;

test('a comment that starts with the prefix is addressed', () => {
  assert.equal(addressed('🤖 approve'), true);
  assert.equal(addressed(':robot: approve'), true);
  assert.equal(addressed('   🤖 approve'), true);
  assert.equal(addressed('\n\n🤖 approve'), true);
});

test('the prefix part-way through, or later on, does not count', () => {
  assert.equal(addressed('Thanks 🤖 approve'), false);
  assert.equal(addressed('Thanks.\n🤖 approve'), false);
  assert.equal(addressed('approve'), false);
});

test('a quote-reply above the prefix is fine; a prefix inside a quote or code is not', () => {
  assert.equal(addressed('> earlier comment\n\n🤖 approve'), true);
  assert.equal(addressed('> 🤖 approve\nthanks'), false);
  assert.equal(addressed('```\n🤖 approve\n```'), false);
});

test("Claude Code's sign-off line is not someone addressing the routine", () => {
  assert.equal(addressed('🤖 Generated with [Claude Code](https://claude.com/claude-code)'), false);
  assert.equal(addressed(':robot: Generated with Claude Code'), false);
  assert.equal(addressed('🤖 _Generated by [Claude Code](https://claude.ai/code)_'), false);
  assert.equal(addressed('Fixed the build.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'), false);
  assert.equal(addressed('🤖 generated tests look wrong, please redo them'), true);
});

test('the request is everything after the prefix, typos and all', () => {
  assert.deepEqual(extractAddressedRequest('🤖 aprove, looks rihgt', PREFIXES), { text: 'aprove, looks rihgt', cut: false });
  assert.equal(extractAddressedRequest('🤖 this is a dupe of #41\nsame stack trace', PREFIXES).text, 'this is a dupe of #41\nsame stack trace');
  assert.equal(extractAddressedRequest('🤖 approve\n@sam can you check?', PREFIXES).text, 'approve');
});

function addressedConfig(extra = {}) {
  return baseConfig({
    routine_login: 'matt',
    routes: [
      {
        name: 'maintainer-says',
        when: 'issue_comment.created',
        if: { addressed_with: PREFIXES, actor: 'maintainer' },
        prompt: 'Respond on {number}: {request}',
      },
      {
        name: 'reporter-replies',
        when: 'issue_comment.created',
        if: { has_label: ['state/drafted'], actor: 'author' },
        prompt: 'Reporter replied on {number}.',
      },
      { name: 'new-issue', when: 'issues.opened', prompt: 'Triage {number}.' },
      { name: 'any-label', when: 'issues.labeled', if: { label: 'state/*' }, prompt: 'Label {label}.' },
    ],
    ...extra,
  });
}

const run = (event, lookup = fakeLookup({ permissions: { matt: 'admin' } })) =>
  matchEvent({ config: addressedConfig(), event, workflowRepo: HUB, hubRepo: HUB, lookup });

test("a maintainer addressing the routine starts it, even from the routine's own account", async () => {
  const r = await run(commentEvent('🤖 aprove please', { actor: 'matt' }));
  assert.equal(r.route, 'maintainer-says');
  assert.match(r.prompt, /<request>\naprove please\n<\/request>/);
});

test("the routine's own comments, posted as that account, start nothing", async () => {
  const r = await run(commentEvent('Thanks for the report. Proposed: needs investigation.', { actor: 'matt' }));
  assert.equal(r.route, null);
  assert.match(r.log, /routine's own account/);
});

test("the routine's own comment can't pass as the reporter's, even when that account opened the issue", async () => {
  const r = await run(commentEvent('Proposed: needs info.', { actor: 'matt', author: 'matt', labels: ['state/drafted'] }));
  assert.equal(r.route, null);
});

test("the routine's own label changes start nothing", async () => {
  const r = await run(issueEvent({ when: 'issues.labeled', label: 'state/drafted', labels: ['state/drafted'], actor: 'matt' }));
  assert.equal(r.route, null);
});

test("an issue opened by the routine's account starts nothing unless addressed", async () => {
  assert.equal((await run(issueEvent({ actor: 'matt', author: 'matt' }))).route, null);
});

test('other people are unaffected by routine_login', async () => {
  const reporter = await run(commentEvent('more detail', { actor: 'reporter', labels: ['state/drafted'] }));
  assert.equal(reporter.route, 'reporter-replies');
  const opened = await run(issueEvent({ actor: 'someone' }));
  assert.equal(opened.route, 'new-issue');
});

test('someone without write access addressing the routine starts nothing', async () => {
  const r = await run(commentEvent('🤖 approve', { actor: 'stranger' }));
  assert.equal(r.route, null);
});

test('addressed_with routes must be maintainer-only, on comments or opened events, and not mix with mentions', () => {
  const errorsFor = (route) => validateConfig(baseConfig({ routes: [route] }));
  assert.ok(
    errorsFor({ name: 'a', when: 'issue_comment.created', if: { addressed_with: ['🤖'] }, prompt: 'x' }).some((e) =>
      e.includes('must also say "actor: maintainer"'),
    ),
  );
  assert.ok(
    errorsFor({ name: 'a', when: 'issues.labeled', if: { addressed_with: ['🤖'], actor: 'maintainer' }, prompt: 'x' }).some((e) =>
      e.includes('only works with a comment event or *.opened'),
    ),
  );
  assert.ok(
    errorsFor({
      name: 'a',
      when: 'issue_comment.created',
      if: { addressed_with: ['🤖'], mentions: ['claude'], actor: 'maintainer' },
      prompt: 'x',
    }).some((e) => e.includes('not both')),
  );
  assert.deepEqual(
    errorsFor({ name: 'a', when: 'issue_comment.created', if: { addressed_with: ['🤖'], actor: 'maintainer' }, prompt: '{request}' }),
    [],
  );
});

test('routine_login must look like a login', () => {
  assert.ok(validateConfig(baseConfig({ routine_login: '@matt' })).some((e) => e.includes('routine_login')));
});
